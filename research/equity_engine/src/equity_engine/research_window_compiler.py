"""Deterministic repeated walk-forward research-window plan compiler (v2).

PLAN artifacts only. No strategy execution, no profitability computation, no
performance thresholds, no optimal window inference, no broker calls, no data
downloads, no test-data access during selection. All sizes, steps, embargoes,
minimum observations, and minimum folds are explicit caller inputs; there are
no hidden defaults.

Structure (repeated WFO + separately untouched FINAL test):

- ``folds``: deterministic repeated chronological folds generated by the shared
  :mod:`wfo_schedule` scheduler (also used by ``walk_forward``). Each fold has
  train, embargo, and validation windows. Fold validation participates in
  selection; it is never the FINAL test.
- ``final_embargo`` + ``final_test`` (role ``untouched_test``): strictly after
  every fold, never participates in model, stock, or parameter selection.

Trust model (explicit):

- Cost and corporate-action inputs are bound as *unverified claims*, never as
  verified evidence. ``CostEvidenceClaim`` mirrors ``CostEvidenceIdentity``
  fields so later convergence (a65) can verify them, but the compiler itself
  records ``verification_status="unverified-claim"`` and requires
  ``historical_actual=False``. A bare ``"0"*64`` fingerprint therefore remains
  an unverified claim; it can never be treated as verified.
- ``CorporateActionClaim`` requires a 64-character hex fingerprint, so an
  arbitrary label such as ``"claimed-ca"`` fails closed at construction.
- PIT membership is bound per instrument via :class:`PITMembershipAttestation`
  (instrument, trade dates, evidence_as_of, source fingerprint), never via one
  opaque string.
- Selection requires a full :class:`SelectionAttestation`. Arbitrary winner
  assertions are rejected. Authorizing the FINAL test requires a valid
  attestation bound into the plan.
- The experiment adapter (:meth:`ResearchWindowPlan.to_experiment_adapter`) is
  lossless: every embargo window and every explicit role is preserved. Direct
  ``ExperimentArtifact`` integration is marked blocked because that schema
  carries a single embargo integer and anonymous validation windows.
"""

